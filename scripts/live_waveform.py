def load_jsonc(path: Path) -> dict:
    txt = path.read_text(encoding="utf-8")
    txt = re.sub(r"(?m)^\s*//.*$", "", txt)
    return json.loads(txt)


def vscode_config() -> dict:
    cfg = {"rate": 10, "refresh": 300, "device": "STM32F103CB",
           "interface": "SWD", "speed": 4000, "gdb": ""}
    try:
        launch = load_jsonc(VSCODE / "launch.json")
        conf = launch["configurations"][0]
        live = conf.get("liveWatch", {})
        cfg["rate"] = int(live.get("samplesPerSecond", cfg["rate"]))
        toolpath = str(conf.get("armToolchainPath", ""))
        if toolpath and "@" not in toolpath:
            for suffix in (".exe", ""):
                cand = Path(toolpath) / ("arm-none-eabi-gdb" + suffix)
                if cand.is_file():
                    cfg["gdb"] = str(cand)
                    break
    except Exception:
        pass
    try:
        settings = json.loads((VSCODE / "settings.json").read_text(encoding="utf-8"))
        cfg["refresh"] = int(settings.get("cortex-debug.liveWatchRefreshRate", cfg["refresh"]))
        cfg["device"] = settings.get("stm32.device", cfg["device"])
        cfg["interface"] = settings.get("stm32.interface", cfg["interface"])
        cfg["speed"] = int(settings.get("stm32.speed", cfg["speed"]))
    except Exception:
        pass
    return cfg


def livewatch_expressions() -> list[str]:
    """Read the expression list persisted by Cortex-Debug in workspaceState."""
    base = Path(os.environ.get("APPDATA", "")) / "Code" / "User" / "workspaceStorage"
    if not base.is_dir():
        return []
    # VS Code encodes the drive colon as %3A; Path.as_uri() does not.
    target = unquote(ROOT.as_uri()).lower().replace("\\", "/")
    for entry in base.iterdir():
        ws = entry / "workspace.json"
        db = entry / "state.vscdb"
        if not (ws.is_file() and db.is_file()):
            continue
        try:
            info = json.loads(ws.read_text(encoding="utf-8"))
            folder = unquote(str(info.get("folder", ""))).lower().replace("\\", "/")
            if folder != target:
                continue
            con = sqlite3.connect(f"file:{db.as_posix()}?mode=ro", uri=True)
            row = con.execute(
                "select value from ItemTable where key=?", ("marus25.cortex-debug",)
            ).fetchone()
            con.close()
            if not row:
                continue
            raw = row[0]
            data = json.loads(raw.decode("utf-8") if isinstance(raw, bytes) else raw)
            tree = data.get("livewatch.watchTree", {})
            return [c["expr"] for c in tree.get("children", []) if c.get("expr")]
        except Exception:
            continue
    return []


def ram_range() -> tuple[int, int]:
    """Derive the writable RAM window from the generated linker script.

    Falls back to a conservative 0x20000000 + 20 KiB (typical Cortex-M SRAM)
    and can always be overridden with --ram-start / --ram-size.
    """
    if RAM_OVERRIDE:
        return RAM_OVERRIDE
    text = ""
    if LD and LD.is_file():
        try:
            text = LD.read_text(encoding="utf-8")
        except Exception:
            pass
    if text:
        regions = re.findall(
            r"([A-Za-z_]\w*)\s*\([^)]*\)\s*:\s*ORIGIN\s*=\s*(0x[0-9A-Fa-f]+)"
            r"\s*,\s*LENGTH\s*=\s*(\d+)([KMGkmg]?)",
            text, re.S,
        )
        best: tuple[int, int, int] | None = None
        mult = {"": 1, "K": 1024, "M": 1024 ** 2, "G": 1024 ** 3}
        for name, origin, length, unit in regions:
            start = int(origin, 16)
            size = int(length) * mult[unit.upper()]
            score = (2 if "ram" in name.lower() else 0) + \
                    (1 if 0x20000000 <= start < 0x30000000 else 0)
            if best is None or score > best[0]:
                best = (score, start, size)
        if best and best[0] > 0:
            return best[1], best[1] + best[2]
    return 0x20000000, 0x20000000 + 20 * 1024


