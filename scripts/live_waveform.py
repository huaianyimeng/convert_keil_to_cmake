def find_executable(name: str, patterns: list[str]) -> str:
    found = shutil.which(name)
    if found:
        return found
    for pattern in patterns:
        for cand in sorted(glob.glob(pattern), reverse=True):
            if Path(cand).is_file():
                return cand
    raise RuntimeError(f"{name} not found; install it or add it to PATH")


@dataclass
class ReadBlock:
    cmd: str
    start: int
    count: int                              # number of bytes to read
    items: list[tuple[int, int, bool]] = field(default_factory=list)  # addr, size, signed


def build_blocks(channels: list[Channel]) -> list[ReadBlock]:
    """One mem8 read per address cluster: fewer J-Link round trips per sample.

    Reading a contiguous byte range and unpacking locally is much cheaper than
    issuing one command per variable (each command costs ~30 ms over winpty),
    which keeps the sampling period stable even at 20-30 Hz.
    """
    points = sorted({(v.addr, v.size, v.signed) for ch in channels for v in ch.infos})
    clusters: list[list[tuple[int, int, bool]]] = []
    current: list[tuple[int, int, bool]] = []
    for p in points:
        if current and p[0] - (current[-1][0] + current[-1][1]) <= 64:
            current.append(p)
        else:
            if current:
                clusters.append(current)
            current = [p]
    if current:
        clusters.append(current)
    blocks = []
    for cluster in clusters:
        start = cluster[0][0]
        end = cluster[-1][0] + cluster[-1][1]
        blocks.append(ReadBlock("mem8", start, end - start, list(cluster)))
    return blocks


def parse_values(line: str) -> list[int]:
    m = VALUE_LINE.search(line)
    if not m:
        return []
    parts = m.group(2).split()
    if not parts or not all(re.fullmatch(r"[0-9A-Fa-f]{1,8}", p) for p in parts):
        return []
    return [int(p, 16) for p in parts]


class InteractiveSource:
    """J-Link Commander through winpty (line buffered, no CPU halt)."""

    def __init__(self, device: str, interface: str, speed: int):
        self.cmd = [
            find_executable("winpty", WINPTY_PATTERNS),
            "-Xallow-non-tty", "-Xplain",
            find_executable("JLink.exe", JLINK_PATTERNS),
            "-AutoConnect", "1", "-Device", device, "-If", interface, "-Speed", str(speed),
        ]
        self.proc = subprocess.Popen(
            self.cmd, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT, text=True, errors="replace", bufsize=1,
        )
        self.lines: queue.Queue[str] = queue.Queue()

        def reader() -> None:
            for line in self.proc.stdout:
                self.lines.put(line.rstrip())

        threading.Thread(target=reader, daemon=True).start()
        startup = []
        deadline = time.time() + 8
        while time.time() < deadline:
            try:
                startup.append(self.lines.get(timeout=0.2))
            except queue.Empty:
                continue
            if any("identified" in s for s in startup):
                break
        if not any("identified" in s for s in startup):
            self.close()
            raise RuntimeError(
                "J-Link did not connect. Is the board powered? "
                "Another tool (VS Code F5 / J-Scope) may be holding the J-Link."
            )

    def read(self, blocks: list[ReadBlock], timeout: float = 0.6) -> list[list[int]]:
        expected = sum(b.count for b in blocks)
        for b in blocks:
            self.proc.stdin.write(f"{b.cmd} 0x{b.start:08X}, {b.count}\n")
        self.proc.stdin.flush()
        vals: list[int] = []
        deadline = time.time() + timeout
        while len(vals) < expected and time.time() < deadline:
            try:
                vals.extend(parse_values(self.lines.get(timeout=0.05)))
            except queue.Empty:
                continue
        if len(vals) < expected:
            while not self.lines.empty():     # discard a partial, misaligned frame
                self.lines.get_nowait()
            return []
        return [vals[:expected]]

    def close(self) -> None:
        try:
            self.proc.stdin.write("exit\n")
            self.proc.stdin.flush()
            self.proc.wait(timeout=3)
        except Exception:
            self.proc.kill()


class BatchSource:
    """Fallback when winpty is unavailable: short sessions, 5 samples per round."""

    def __init__(self, device: str, interface: str, speed: int, rate: int, per_round: int = 5):
        self.cmd = [
            find_executable("JLink.exe", JLINK_PATTERNS),
            "-AutoConnect", "1", "-Device", device, "-If", interface,
            "-Speed", str(speed), "-ExitOnError", "1",
        ]
        self.interval = max(1, int(1000 / rate))
        self.per_round = per_round

    def read(self, blocks: list[ReadBlock], timeout: float = 0.6) -> list[list[int]]:
        expected = sum(b.count for b in blocks)
        lines: list[str] = []
        for i in range(self.per_round):
            for b in blocks:
                lines.append(f"{b.cmd} 0x{b.start:08X}, {b.count}")
            if i != self.per_round - 1:
                lines.append(f"sleep {self.interval}")
        lines.append("exit")
        try:
            proc = subprocess.run(
                self.cmd, input="\n".join(lines) + "\n",
                capture_output=True, text=True, errors="replace", timeout=15,
            )
        except subprocess.TimeoutExpired:
            return []
        vals: list[int] = []
        for line in (proc.stdout + proc.stderr).splitlines():
            vals.extend(parse_values(line))
        groups = []
        for i in range(0, len(vals) - expected + 1, expected):
            groups.append(vals[i:i + expected])
        return groups[:self.per_round]

    def close(self) -> None:
        pass


