class Sampler:
    def __init__(self, channels: list[Channel], rate: int, device: str,
                 interface: str, speed: int, window: int, refresh: int = 300):
        self.channels = channels
        self.rate = rate
        self.window = window
        self.refresh = refresh
        self.lock = threading.Lock()
        self.points: list[tuple[float, list[float]]] = []
        self.seq = 0
        self.paused = False
        self.status = "connecting"
        self.error = ""
        self.blocks = build_blocks(channels)
        self.t0 = time.time()
        self.stop_evt = threading.Event()
        try:
            self.source = InteractiveSource(device, interface, speed)
            self.mode = "winpty streaming"
        except RuntimeError as exc:
            if "winpty" in str(exc).lower():
                self.source = BatchSource(device, interface, speed, rate)
                self.mode = "batch fallback"
                self.status = "running"
            else:
                raise
        except Exception:
            self.source = BatchSource(device, interface, speed, rate)
            self.mode = "batch fallback"
            self.status = "running"
        else:
            self.status = "running"
        self.thread = threading.Thread(target=self._loop, daemon=True)
        self.thread.start()

    def _emit(self, when: float, values: list[int], blocks: list[ReadBlock] | None = None) -> None:
        value_map: dict[tuple[int, int], float] = {}
        idx = 0
        for b in (blocks if blocks is not None else self.blocks):
            raw = bytes(values[idx:idx + b.count])
            idx += b.count
            for addr, size, signed in b.items:
                off = addr - b.start
                if off < 0 or off + size > len(raw):
                    continue
                value_map[(addr, size)] = int.from_bytes(
                    raw[off:off + size], "little", signed=signed
                )
        row: list[float] = []
        with self.lock:
            for ch in self.channels:
                env = dict(SAFE_BUILTINS)
                for i, info in enumerate(ch.infos):
                    env[f"_v{i}"] = value_map.get((info.addr, info.size), 0)
                try:
                    row.append(float(eval(ch.code, env, {})))
                except Exception:
                    row.append(float("nan"))
            self.points.append((when - self.t0, row))
            max_points = self.rate * max(self.window, 600)
            if len(self.points) > max_points:
                del self.points[:len(self.points) - max_points]
            self.seq += 1

    def _loop(self) -> None:
        period = 1.0 / self.rate
        next_t = time.monotonic()
        while not self.stop_evt.is_set():
            if self.paused:
                time.sleep(0.05)
                next_t = time.monotonic() + period
                continue
            blocks = self.blocks
            try:
                groups = self.source.read(blocks)
            except Exception as exc:
                self.error = str(exc)
                self.status = "error"
                time.sleep(0.5)
                continue
            base = time.time()
            expected = sum(b.count for b in blocks)
            for i, group in enumerate(groups):
                if len(group) != expected:
                    continue
                when = base - (len(groups) - 1 - i) / self.rate
                self._emit(when, group, blocks)
            if groups:
                self.status = "running"
                self.error = ""
            next_t += period
            time.sleep(max(0.0, next_t - time.monotonic()))

    def rebuild(self) -> None:
        with self.lock:
            self.blocks = build_blocks(self.channels)

    def add(self, expr: str) -> None:
        color = PALETTE[len(self.channels) % len(PALETTE)]
        ch = compile_channel(expr, color)
        with self.lock:
            self.channels.append(ch)
            self.points.clear()
        self.rebuild()

    def remove(self, index: int) -> None:
        with self.lock:
            if 0 <= index < len(self.channels):
                self.channels.pop(index)
                self.points.clear()
        self.rebuild()

    def snapshot(self, since: int) -> dict:
        with self.lock:
            n = max(0, self.seq - since)
            pts = self.points[-n:] if n else []
            return {
                "seq": self.seq,
                "points": [[round(t, 4), vals] for t, vals in pts],
                "paused": self.paused,
                "status": self.status,
                "error": self.error,
                "mode": self.mode,
            }

    def config(self) -> dict:
        with self.lock:
            return {
                "channels": [
                    {"expr": c.expr, "color": c.color, "visible": c.visible}
                    for c in self.channels
                ],
                "rate": self.rate,
                "refresh": self.refresh,
                "poll": self.refresh,
                "window": self.window,
                "mode": self.mode,
            }

    def csv_bytes(self) -> bytes:
        with self.lock:
            exprs = [c.expr for c in self.channels]
            pts = list(self.points)
        buf = io.StringIO()
        writer = csv.writer(buf)
        writer.writerow(["time_s"] + exprs)
