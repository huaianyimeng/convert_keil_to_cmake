@dataclass
class VarInfo:
    ref: str
    addr: int
    size: int
    signed: bool


@dataclass
class Channel:
    expr: str
    code: object
    infos: list[VarInfo]
    color: str
    visible: bool = True

    @property
    def label(self) -> str:
        return self.expr


def resolve_refs(refs: list[str]) -> list[VarInfo]:
    """Resolve addresses/sizes/types with arm-none-eabi-gdb, no target needed."""
    cmd = [GDB, "-q", "-batch", str(ELF), "-ex", "set pagination off"]
    for i, ref in enumerate(refs):
        cmd += [
            "-ex", f"echo @@{i}@@\\n",
            "-ex", f"p/x &{ref}",
            "-ex", f"p sizeof({ref})",
            "-ex", f"ptype {ref}",
        ]
    proc = subprocess.run(cmd, capture_output=True, text=True, errors="replace", timeout=60)
    out = proc.stdout + proc.stderr
    lo, hi = ram_range()
    infos = []
    for i, ref in enumerate(refs):
        m = re.search(rf"@@{i}@@(.*?)(?=@@{i + 1}@@|\Z)", out, re.S)
        seg = m.group(1) if m else ""
        vals = re.findall(r"\$[0-9]+\s*=\s*([^\n]+)", seg)
        typ = re.search(r"type\s*=\s*([^\n]+)", seg)
        if len(vals) < 2 or not typ:
            raise ValueError(f"cannot resolve {ref!r} in ELF (typo, local variable, or pointer chain)")
        try:
            maddr = re.search(r"0x[0-9A-Fa-f]+", vals[0])
            addr = int(maddr.group(0), 16) if maddr else int(vals[0].strip(), 0)
            size = int(vals[1].strip(), 0)
        except (ValueError, AttributeError) as exc:
            raise ValueError(f"cannot parse GDB answer for {ref!r}: {vals[:2]}") from exc
        if not (lo <= addr < hi):
            raise ValueError(
                f"{ref!r} resolves to 0x{addr:08X}, outside RAM 0x{lo:08X}-0x{hi:08X}. "
                "Pointer/member chains through a pointer cannot be resolved offline."
            )
        if size not in (1, 2, 4):
            raise ValueError(f"{ref!r} is {size} bytes; only 1/2/4-byte scalars are supported")
        t = typ.group(1).lower()
        signed = not any(k in t for k in ("unsigned", "uint", "bool", "size_t"))
        infos.append(VarInfo(ref, addr, size, signed))
    return infos


def compile_channel(expr: str, color: str) -> Channel:
    refs: list[str] = []
    seen: dict[str, str] = {}

    def substitute(match: re.Match) -> str:
        tok = match.group(0)
        rest = expr[match.end():].lstrip()
        if tok in FUNCS and rest.startswith("("):
            return tok
        if tok not in seen:
            seen[tok] = f"_v{len(refs)}"
            refs.append(tok)
        return seen[tok]

    pyexpr = REF_RE.sub(substitute, expr)
    if not refs:
        raise ValueError(f"expression {expr!r} contains no variable")
    try:
        code = compile(pyexpr, "<wave-expr>", "eval")
    except SyntaxError as exc:
        raise ValueError(f"invalid expression {expr!r}: {exc}") from exc
    infos = resolve_refs(refs)
    # Smoke-test evaluation with placeholder zeros to catch bad names early.
    env = dict(SAFE_BUILTINS)
    env.update({f"_v{i}": 0 for i in range(len(refs))})
    try:
        eval(code, env, {})
    except Exception as exc:
        raise ValueError(f"expression {expr!r} cannot be evaluated: {exc}") from exc
    return Channel(expr, code, infos, color)


