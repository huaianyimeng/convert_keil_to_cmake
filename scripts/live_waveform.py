#!/usr/bin/env python3
"""Portable live waveform viewer for Cortex Live Watch expressions.

Shipped by the convert-keil-to-cmake skill into every generated project's
scripts/ directory. J-Scope can plot variables but not expressions; this tool
reuses the VS Code Cortex-Debug expression list, sample rate and refresh rate,
resolves each C expression to a RAM address with arm-none-eabi-gdb (offline),
then reads those addresses in the background through J-Link while the CPU keeps
running. A browser Canvas plots every channel in its own colour with smooth
60 fps scrolling.

Project-agnostic: the ELF, linker script, GDB, MCU and starter expressions are
auto-discovered from the generated project (or given with CLI options). No
third-party Python packages are required. J-Link Commander is driven through
winpty so its output is line buffered and truly streaming.

Usage:
    python scripts/live_waveform.py                 # auto-discover, open browser
    python scripts/live_waveform.py --expr "angle*360/65536" --expr raw
    python scripts/live_waveform.py --rate 20 --window 30 --port 8765
    python scripts/live_waveform.py --list-symbols # candidate scalar variables
    python scripts/live_waveform.py --headless --duration 5
    python scripts/live_waveform.py --elf build/fw.elf --ld cmake/flash.ld

Note: J-Link is exclusive. Do not run this tool and a VS Code F5 debug session
at the same time.
"""

