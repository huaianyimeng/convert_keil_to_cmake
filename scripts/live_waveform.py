def find_elf(explicit: str | None = None) -> Path | None:
    if explicit:
        return Path(explicit)
    for pattern in ("build/*.elf", "*.elf", "build/*/*.elf"):
        found = sorted(ROOT.glob(pattern))
        if found:
            return found[0]
    return None


def find_ld(explicit: str | None = None) -> Path | None:
    if explicit:
        return Path(explicit)
    for pattern in ("cmake/*.ld", "*.ld", "linker/*.ld", "ld/*.ld", "cmake/*.ld.in"):
        found = sorted(ROOT.glob(pattern))
        if found:
            return found[0]
    return None


def auto_expressions(elf: Path, limit: int = 4) -> list[str]:
    """Pick a few global/static scalars from the ELF as starter channels.

    Only 1/2/4-byte objects are usable, and duplicate static names are skipped
    because GDB cannot disambiguate them without an explicit file qualifier.
    """
    nm = shutil.which("arm-none-eabi-nm") or str(Path(GDB).parent / "arm-none-eabi-nm")
    try:
        out = subprocess.run(
            [nm, "--print-size", "--defined-only", "-n", str(elf)],
            capture_output=True, text=True, errors="replace", timeout=30,
        ).stdout
    except (OSError, subprocess.SubprocessError):
        return []
    rows = []
    for line in out.splitlines():
        m = re.match(
            r"^\s*([0-9A-Fa-f]{8,16})\s+([0-9A-Fa-f]{8,16})\s+([bBdD])\s+(\S+)$",
            line,
        )
        if m:
            rows.append((int(m.group(2), 16), m.group(3), m.group(4)))
    counts: dict[str, int] = {}
    for _, _, name in rows:
        counts[name] = counts.get(name, 0) + 1
    dynamic = ("angle", "pos", "vel", "speed", "tick", "cnt", "count", "value",
               "temp", "adc", "pwm", "curr", "volt", "state", "err", "raw",
               "meas", "rpm", "duty", "phase", "target", "feedback")
    scored: list[tuple[int, str]] = []
    for size, typ, name in rows:
        if size not in (1, 2, 4) or counts[name] != 1:
            continue
        if not re.fullmatch(r"[A-Za-z_]\w*", name) or name.startswith("_"):
            continue
        score = (2 if typ in "bB" else 0) + \
                (2 if any(k in name.lower() for k in dynamic) else 0)
        scored.append((-score, name))
    scored.sort()
    return [name for _, name in scored[:limit]]

# C-ish variable references: 'file.c'::name, name.member, name->member
REF_RE = re.compile(
    r"(?:'[A-Za-z0-9_./\\-]+\.[ch]'::)?[A-Za-z_]\w*(?:(?:\.|->)[A-Za-z_]\w*)*"
)
FUNCS = {
    "abs", "min", "max", "round", "sqrt", "sin", "cos", "tan",
    "floor", "ceil", "pow", "fabs", "pi",
}
SAFE_BUILTINS = {
    "abs": abs, "min": min, "max": max, "round": round,
    "sqrt": math.sqrt, "sin": math.sin, "cos": math.cos, "tan": math.tan,
    "floor": math.floor, "ceil": math.ceil, "pow": math.pow,
    "fabs": math.fabs, "pi": math.pi, "__builtins__": {},
}
VALUE_LINE = re.compile(r"([0-9A-Fa-f]{8})\s*=\s*(.*)$")


